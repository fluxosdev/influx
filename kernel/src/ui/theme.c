#include "ui.h"

struct theme theme;
const color_t accent_colors[8] = { 0xFF007AFF, 0xFFAF52DE, 0xFFFF2D55, 0xFFFF3B30, 0xFFFF9500, 0xFFFFCC00, 0xFF34C759, 0xFF8E8E93 };
const char *accent_names[8] = { "Blue", "Purple", "Pink", "Red", "Orange", "Yellow", "Green", "Graphite" };

void theme_apply(bool dark, int accent_index) {
    struct theme t = theme;
    t.dark = dark;
    t.accent_index = CLAMP(accent_index, 0, 7);
    t.accent = accent_colors[t.accent_index];
    t.accent_text = RGB(255, 255, 255);
    if (!dark) {
        t.bg = RGB(0xFF, 0xFF, 0xFF); t.bg_secondary = RGB(0xF5, 0xF5, 0xF7); t.sidebar_bg = RGB(0xEE, 0xEE, 0xF0);
        t.text = RGB(0x1D, 0x1D, 0x1F); t.text_secondary = RGB(0x6E, 0x6E, 0x73); t.text_tertiary = RGB(0xA1, 0xA1, 0xA6); t.text_disabled = RGB(0xC7, 0xC7, 0xCC);
        t.separator = RGB(0xE5, 0xE5, 0xEA); t.border = RGB(0xD1, 0xD1, 0xD6);
        t.control_bg = RGB(0xFF, 0xFF, 0xFF); t.control_border = RGB(0xC9, 0xC9, 0xCE); t.control_hover = RGB(0xF2, 0xF2, 0xF7);
        t.titlebar = RGB(0xE9, 0xE9, 0xEB); t.titlebar_unfocused = RGB(0xF6, 0xF6, 0xF6); t.titlebar_line = RGB(0xD0, 0xD0, 0xD3);
        t.title_text = RGB(0x3A, 0x3A, 0x3C); t.title_text_unfocused = RGB(0xA8, 0xA8, 0xAC);
        t.menubar_bg = RGBA(0xFF, 0xFF, 0xFF, 0xB8); t.menubar_text = RGB(0x1D, 0x1D, 0x1F);
        t.menu_bg = RGBA(0xF6, 0xF6, 0xF8, 0xF4); t.menu_text = RGB(0x1D, 0x1D, 0x1F); t.menu_sep = RGBA(0, 0, 0, 0x22);
        t.dock_bg = RGBA(0xFF, 0xFF, 0xFF, 0x5C); t.dock_border = RGBA(0xFF, 0xFF, 0xFF, 0x70);
        t.selection = t.accent; t.selection_inactive = RGB(0xDC, 0xDC, 0xE0);
        t.input_bg = RGB(0xFF, 0xFF, 0xFF); t.input_border = RGB(0xC9, 0xC9, 0xCE);
    } else {
        t.bg = RGB(0x1E, 0x1E, 0x20); t.bg_secondary = RGB(0x28, 0x28, 0x2B); t.sidebar_bg = RGB(0x2A, 0x2A, 0x2D);
        t.text = RGB(0xF5, 0xF5, 0xF7); t.text_secondary = RGB(0x98, 0x98, 0x9D); t.text_tertiary = RGB(0x6E, 0x6E, 0x73); t.text_disabled = RGB(0x4A, 0x4A, 0x4E);
        t.separator = RGB(0x3A, 0x3A, 0x3C); t.border = RGB(0x45, 0x45, 0x48);
        t.control_bg = RGB(0x3A, 0x3A, 0x3E); t.control_border = RGB(0x50, 0x50, 0x54); t.control_hover = RGB(0x45, 0x45, 0x4A);
        t.titlebar = RGB(0x32, 0x32, 0x35); t.titlebar_unfocused = RGB(0x29, 0x29, 0x2B); t.titlebar_line = RGB(0x12, 0x12, 0x14);
        t.title_text = RGB(0xE5, 0xE5, 0xE7); t.title_text_unfocused = RGB(0x7A, 0x7A, 0x7E);
        t.menubar_bg = RGBA(0x10, 0x10, 0x12, 0x90); t.menubar_text = RGB(0xF5, 0xF5, 0xF7);
        t.menu_bg = RGBA(0x2C, 0x2C, 0x2E, 0xF4); t.menu_text = RGB(0xF5, 0xF5, 0xF7); t.menu_sep = RGBA(0xFF, 0xFF, 0xFF, 0x22);
        t.dock_bg = RGBA(0x10, 0x10, 0x14, 0x60); t.dock_border = RGBA(0xFF, 0xFF, 0xFF, 0x28);
        t.selection = t.accent; t.selection_inactive = RGB(0x45, 0x45, 0x4A);
        t.input_bg = RGB(0x1C, 0x1C, 0x1E); t.input_border = RGB(0x50, 0x50, 0x54);
    }
    if (t.accent_index == 5) t.accent_text = RGB(0x1D, 0x1D, 0x1F);   /* yellow needs dark text */
    if (!t.wallpaper_top) { t.wallpaper_top = RGB(0x58, 0x94, 0xC4); t.wallpaper_bottom = RGB(0x36, 0x6A, 0x98); }
    theme = t;
}
void theme_set_wallpaper(color_t top, color_t bottom) { theme.wallpaper_top = top; theme.wallpaper_bottom = bottom; }
